namespace FileFlow.Core.Localization;

/// <summary>Language codes supported by the UI. English is the default.</summary>
public static class AppLanguages
{
    public const string English = "en";

    public const string Chinese = "zh-CN";

    public const string Default = English;

    public static IReadOnlyList<string> All { get; } = [English, Chinese];

    /// <summary>Maps any stored value onto a supported language code; unknown values fall back to English.</summary>
    public static string Normalize(string? language)
    {
        if (string.IsNullOrWhiteSpace(language))
        {
            return Default;
        }

        var trimmed = language.Trim();
        if (trimmed.StartsWith("zh", StringComparison.OrdinalIgnoreCase))
        {
            return Chinese;
        }

        return English;
    }
}

